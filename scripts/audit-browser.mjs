import { chromium, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const solution=readFileSync(new URL('../tests/fixtures/robotSolution.ts',import.meta.url),'utf8').split('`')[1];
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1280,height:900},reducedMotion:'reduce'});
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
 await page.addInitScript(()=>{Math.random=()=>0});
 await page.goto(process.env.APP_URL || 'http://127.0.0.1:5174');
 await expect(page.getByRole('heading',{name:'Choose Your Challenge'})).toBeVisible();
 await page.getByRole('button',{name:'Attempt Challenge'}).first().focus();
 await page.keyboard.press('Enter');
 await expect(page.locator('.cipher-display code')).toHaveText('UHDG LQ WKH QDPH RI BRXU ORUG');
 await page.getByLabel('Your decoded message').fill('wrong');
 await page.getByRole('button',{name:'Submit',exact:true}).click();
 await expect(page.locator('.feedback')).toContainText('Not quite');
 for(let n=1;n<=3;n++){await page.getByRole('button',{name:'Need help?'}).click();await expect(page.locator('.hint-heading')).toContainText(`Hints used: ${n} / 3`)}
 await page.getByLabel('Your decoded message').fill(' read, IN  the name of your LORD. ');
 await page.getByRole('button',{name:'Submit',exact:true}).click();
 await expect(page.locator('.prize-callout')).toBeVisible();
 await page.getByRole('button',{name:'New Challenger'}).click();
 await page.getByRole('button',{name:'Attempt Challenge'}).first().click();
 await expect(page.getByLabel('Your decoded message')).toHaveValue('');
 await expect(page.locator('.hint-heading')).toContainText('0 / 3');
 await page.getByRole('button',{name:'Back to challenges'}).click();
 await page.getByRole('button',{name:'Attempt Challenge'}).nth(1).click();
 const editor=page.getByLabel('Robot OS program');
 const run=async code=>{await editor.fill(code);await page.getByRole('button',{name:'Run program'}).click()};
 await run('MOVE()');
 await expect(page.getByRole('status')).toContainText('SYNTAX ERROR');
 await run('MOVE();');
 await expect(page.getByRole('status')).toContainText('Collision');
 await run('while (true) {}');
 await expect(page.getByRole('status')).toContainText('Possible infinite loop');
 await run('TURN_LEFT(); MOVE(2); TURN_RIGHT(); MOVE(2); TURN_RIGHT(); MOVE(2); TURN_LEFT(); MOVE(2); TURN_LEFT(); MOVE(4);');
 await expect(page.getByRole('status')).toContainText('ONE TEST DID NOT PASS');
 await run('while (true) { TURN_LEFT(); }');
 await page.getByRole('button',{name:'Stop',exact:false}).click();
 await run('');
 await expect(page.getByRole('status')).toContainText('MISSION INCOMPLETE');
 await page.waitForTimeout(100);
 await expect(page.getByRole('status')).toContainText('MISSION INCOMPLETE');
 await run(solution+'TURN_RIGHT();');
 await expect(page.getByRole('status')).toContainText('ALMOST THERE');
 await run(solution);
 await expect(page.locator('.prize-callout')).toBeVisible({timeout:10000});
 await page.getByRole('button',{name:'New Challenger'}).click();
 await page.getByRole('button',{name:'Attempt Challenge'}).nth(1).click();
 await expect(editor).toContainText('// Guide the robot');
 await editor.fill('// line\n'.repeat(70));
 await editor.evaluate(el=>{el.scrollTop=400;el.dispatchEvent(new Event('scroll'))});
 expect(await page.locator('.line-numbers').evaluate(el=>el.scrollTop)).toBe(400);
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('SYSTEM READY');
 for(const width of [1280,1024,768,390,320]){
   await page.setViewportSize({width,height:900});
   expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 }
 await page.setViewportSize({width:1280,height:900});
 await page.screenshot({path:'test-results/verified-robot.png',fullPage:true});
 await page.emulateMedia({reducedMotion:'no-preference'});
 await run('TURN_LEFT(); MOVE();');
 await expect(page.getByRole('status')).toContainText('MISSION INCOMPLETE');
 expect(await page.locator('.robot-position').evaluate(el=>getComputedStyle(el).transitionDuration)).toBe('0.28s');
 await page.emulateMedia({reducedMotion:'reduce'});
 expect(await page.locator('.robot-position').evaluate(el=>getComputedStyle(el).transitionDuration)).toBe('1e-05s');
 await page.getByRole('button',{name:'Back to challenges'}).click();
 expect(await page.locator('img').evaluateAll(images=>images.every(img=>img.complete&&img.naturalWidth>0))).toBe(true);
 await page.screenshot({path:'test-results/verified-home.png',fullPage:true});
 expect(errors).toEqual([]);
 console.log('PASS: cipher, robot errors/success/reset/stop, keyboard, artwork, responsive layout, reduced motion; no browser errors.');
} finally {await browser.close()}
